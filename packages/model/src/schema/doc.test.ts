/**
 * U1.1.2 schema-doc: renderSchemaRegion / spliceGeneratedRegion. Expected values come from the design
 * doc (§6 output format, §8 invariants SD-1..SD-11), never from running the renderer: the faithful
 * projection is built here from NODE_LABELS / EDGE_TYPES, and the layout oracle is a hand-written literal.
 * Whether the committed region equals the render is the `check:schema` gate's job, not this file's.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import * as fc from 'fast-check';
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';

import {
  CPG_SCHEMA,
  EDGE_TYPES,
  GENERATED_BEGIN,
  GENERATED_END,
  NODE_LABELS,
  renderSchemaRegion,
  spliceGeneratedRegion,
  type EdgeTypeSpec,
  type NodeLabelSpec,
  type PropertySpec,
} from '../index';
import * as enums from './enums';

/* oxlint-disable typescript/no-unsafe-type-assertion, typescript/no-unnecessary-type-parameters -- test-only: YAML.parse returns any; each call site names the shape it expects. */
const parseAs = <T>(text: string, version: '1.1' | '1.2' = '1.2'): T =>
  parse(text, { version }) as T;
/* oxlint-enable typescript/no-unsafe-type-assertion, typescript/no-unnecessary-type-parameters */

const DASHES = '# ' + '-'.repeat(93);
const BEGIN_LINE = `${GENERATED_BEGIN} (fixture)\n`;
const END_LINE = `${GENERATED_END}\n`;

const prop = (over: Partial<PropertySpec> = {}): PropertySpec => ({
  name: 'p',
  type: 'string',
  cardinality: 'one',
  golden: 'include',
  owner: 'code',
  doc: '',
  ...over,
});
const node = (over: Partial<NodeLabelSpec> = {}): NodeLabelSpec => ({
  label: 'A',
  cpgCoLabel: false,
  hasFileProperty: true,
  ownership: 'file-owned',
  write: 'delete-create',
  key: ['id'],
  properties: [],
  firstWrittenIn: 'M0.0',
  doc: '',
  ...over,
});
const edge = (over: Partial<EdgeTypeSpec> = {}): EdgeTypeSpec => ({
  type: 'E',
  from: ['A'],
  to: ['A'],
  ownership: 'file-owned',
  write: 'delete-create',
  properties: [],
  firstWrittenIn: 'M0.0',
  doc: '',
  ...over,
});
const fixture = (nodes: NodeLabelSpec[], edges: EdgeTypeSpec[] = [], version = 7) => ({
  version,
  nodes,
  edges,
});

/** Test-local identity table (D6 names): deliberately not the renderer's own map. */
const ENUM_BY_NAME: ReadonlyArray<readonly [string, readonly string[]]> = [
  ['node_status', enums.NODE_STATUS],
  ['resolution_status', enums.RESOLUTION_STATUS],
  ['inherits_relation', enums.INHERITS_RELATION],
  ['type_decl_kind', enums.TYPE_DECL_KIND],
  ['method_kind', enums.METHOD_KIND],
  ['call_kind', enums.CALL_KIND],
];
const enumName = (values: readonly string[] | undefined): string | undefined =>
  ENUM_BY_NAME.find(([, v]) => v === values)?.[0];

describe('renderSchemaRegion layout (design §6)', () => {
  it('prints a one-node, zero-edge schema exactly as the normative format says', () => {
    const out = renderSchemaRegion(
      fixture([
        node({
          doc: 'Doc "A".',
          properties: [
            prop({ name: 'id', doc: 'The id.' }),
            prop({
              name: 'status',
              cardinality: 'zeroOrOne',
              golden: 'redact',
              owner: 'filesystem',
              enumValues: enums.NODE_STATUS,
            }),
            // no enum and no doc: the row ends with an unpadded last cell, no comma (design §6)
            prop({ name: 'loc', owner: 'code', doc: '' }),
          ],
        }),
      ]),
    );
    expect(out).toBe(
      [
        '# Generated by `bun run schema:doc` from CPG_SCHEMA (packages/model/src/schema), schema version 7. Do not edit by hand.',
        DASHES,
        '# Node labels (1)',
        DASHES,
        'nodes:',
        '  - label: A',
        '    cpg_co_label: false',
        '    has_file_property: true',
        '    ownership: file-owned',
        '    write: delete-create',
        '    key: [id]',
        '    properties:',
        '      - { name: id,     type: string, cardinality: one,       golden: include, owner: code,       doc: "The id." }',
        '      - { name: status, type: string, cardinality: zeroOrOne, golden: redact,  owner: filesystem, enum: node_status }',
        '      - { name: loc,    type: string, cardinality: one,       golden: include, owner: code }',
        '    doc: "Doc \\"A\\"."',
        '',
        DASHES,
        '# Edge types (0)',
        DASHES,
        'edges: []',
        '',
      ].join('\n'),
    );
  });

  it('prints an edge with from/to flow lists, empty properties and key: [] for a keyless node', () => {
    const out = renderSchemaRegion(
      fixture(
        [node({ key: [] }), node({ label: 'B' })],
        [edge({ type: 'LINKS', from: ['A', 'B'], to: ['B'], doc: 'x' })],
      ),
    );
    expect(out).toContain('    key: []\n');
    expect(out).toContain('    properties: []\n');
    expect(out).toContain(
      [
        '  - type: LINKS',
        '    from: [A, B]',
        '    to: [B]',
        '    ownership: file-owned',
        '    write: delete-create',
        '    properties: []',
        '    doc: "x"',
        '',
      ].join('\n'),
    );
    // entries are separated by exactly one blank line; an empty doc is omitted (no `doc:` key)
    expect(out).toContain('    properties: []\n\n  - label: B\n');
    expect(out).not.toMatch(/^ {4}doc: ""/m);
  });

  it('keeps entries in schema order (no sorting) and takes counts and version from the data', () => {
    const out = renderSchemaRegion(
      fixture([node({ label: 'Z' }), node({ label: 'A' }), node({ label: 'M' })], [], 12),
    );
    expect(out.indexOf('label: Z')).toBeLessThan(out.indexOf('label: A'));
    expect(out.indexOf('label: A')).toBeLessThan(out.indexOf('label: M'));
    expect(out).toContain('# Node labels (3)');
    expect(out.split('\n')[0]).toContain('schema version 12.');
  });

  it('is deterministic, LF-only, ends with one newline and has no trailing whitespace (SD-1)', () => {
    const a = renderSchemaRegion(CPG_SCHEMA);
    expect(renderSchemaRegion(CPG_SCHEMA)).toBe(a);
    expect(a).not.toContain('\r');
    expect(a.endsWith('\n')).toBe(true);
    expect(a.endsWith('\n\n')).toBe(false);
    expect(a).not.toMatch(/[ \t]$/m);
  });
});

const propRow = (p: PropertySpec): Record<string, unknown> => ({
  name: p.name,
  type: p.type,
  cardinality: p.cardinality,
  golden: p.golden,
  owner: p.owner,
  ...(p.enumValues ? { enum: enumName(p.enumValues) } : {}),
  ...(p.doc ? { doc: p.doc } : {}),
});
const withDoc = (doc: string) => (doc ? { doc } : {});

describe('renderSchemaRegion faithfulness to CPG_SCHEMA (SD-4, SD-5, SD-11)', () => {
  // Independent projection straight from the schema data (snake_case names per the YAML doc).
  const nodeProjection = NODE_LABELS.map((n) => ({
    label: n.label,
    cpg_co_label: n.cpgCoLabel,
    has_file_property: n.hasFileProperty,
    ownership: n.ownership,
    write: n.write,
    key: [...n.key],
    properties: n.properties.map(propRow),
    ...withDoc(n.doc),
  }));
  const edgeProjection = EDGE_TYPES.map((e) => ({
    type: e.type,
    from: [...e.from],
    to: [...e.to],
    ownership: e.ownership,
    write: e.write,
    properties: e.properties.map(propRow),
    ...withDoc(e.doc),
  }));

  it('parses back to exactly the schema, nothing more, nothing less', () => {
    const doc = parseAs<Record<string, unknown>>(renderSchemaRegion(CPG_SCHEMA));
    expect(Object.keys(doc)).toEqual(['nodes', 'edges']);
    expect(doc.nodes).toEqual(nodeProjection);
    expect(doc.edges).toEqual(edgeProjection);
  });

  it('gives every property row an owner and both owners show up on FILE', () => {
    const out = renderSchemaRegion(CPG_SCHEMA);
    const total = [...NODE_LABELS, ...EDGE_TYPES].reduce((s, x) => s + x.properties.length, 0);
    expect(out.match(/\bowner: (filesystem|code)\b/g)).toHaveLength(total);
    const doc = parseAs<{
      nodes: { label: string; properties: { name: string; owner: string }[] }[];
    }>(out);
    const file = doc.nodes.find((n) => n.label === 'FILE')!;
    // design §3 decision 1 / 07-milestones: walker owns these five; the rest of FILE is code-owned
    expect(file.properties.filter((p) => p.owner === 'filesystem').map((p) => p.name)).toEqual([
      'path',
      'name',
      'language',
      'content_hash',
      'revision_id',
    ]);
    expect(file.properties.filter((p) => p.owner === 'code').map((p) => p.name)).toEqual([
      'interface_hash',
      'status',
      'version',
      'indexed_at',
      'loc',
    ]);
  });

  it('prints the same enum name for CALLS.status and IMPORTS.status', () => {
    const doc = parseAs<{
      edges: { type: string; properties: { name: string; enum?: string }[] }[];
    }>(renderSchemaRegion(CPG_SCHEMA));
    for (const t of ['CALLS', 'IMPORTS']) {
      const e = doc.edges.find((x) => x.type === t)!;
      expect(e.properties.find((p) => p.name === 'status')?.enum).toBe('resolution_status');
    }
  });
});

describe('renderSchemaRegion enum identity (SD-6)', () => {
  it.each(ENUM_BY_NAME.map(([name, values]) => [name, values] as const))(
    'names the %s enum by identity',
    (name, values) => {
      const out = renderSchemaRegion(
        fixture([node({ properties: [prop({ enumValues: values })] })]),
      );
      expect(out).toContain(`enum: ${name}`);
    },
  );

  it('has a name for every array exported by enums.ts', () => {
    const exported = Object.values(enums).filter(Array.isArray);
    expect(exported).toHaveLength(ENUM_BY_NAME.length);
  });

  it('throws naming X.p when enumValues is a fresh array with the same contents', () => {
    const fresh = [...enums.NODE_STATUS];
    expect(() =>
      renderSchemaRegion(
        fixture([node({ label: 'X', properties: [prop({ name: 'p', enumValues: fresh })] })]),
      ),
    ).toThrow('schema-doc: X.p enumValues is not a declared enum (enums.ts)');
  });

  it('applies the same check to edge properties', () => {
    expect(() =>
      renderSchemaRegion(
        fixture(
          [node()],
          [edge({ type: 'Y', properties: [prop({ name: 'q', enumValues: ['a'] })] })],
        ),
      ),
    ).toThrow('schema-doc: Y.q enumValues is not a declared enum (enums.ts)');
  });
});

describe('renderSchemaRegion quoting (property-based, SD-4)', () => {
  const hostile = fc.constantFrom(
    'true',
    'false',
    'null',
    'on',
    'off',
    'Yes',
    'No',
    'y',
    'n',
    '~',
    'string[]',
    '1abc',
    '123',
    'a: b',
    '# c',
    '- d',
    '',
    ' lead',
    'trail ',
    'x,y',
    '[z]',
    '{w}',
    '"q"',
    "it's",
    'a\\b',
    'two\nlines',
    ' ',
    '😀 astral',
    'plain_word-1',
  );
  const text = fc.oneof(
    hostile,
    fc.string({ unit: 'grapheme-ascii' }),
    fc.string({ unit: 'grapheme' }),
  );

  it('round-trips arbitrary labels, scalars, lists, property names and docs through YAML', () => {
    fc.assert(
      fc.property(
        text,
        text,
        text,
        text,
        text,
        fc.array(text, { maxLength: 3 }),
        (label, propName, nodeDoc, propDoc, edgeType, keys) => {
          const out = renderSchemaRegion(
            fixture(
              [
                node({
                  label,
                  key: keys,
                  doc: nodeDoc,
                  properties: [prop({ name: propName, doc: propDoc })],
                }),
              ],
              [edge({ type: edgeType, from: keys, to: [label] })],
            ),
          );
          // YAML 1.1 readers (PyYAML) treat on/off/yes/no/y/n as booleans: the output must survive both versions (design §6).
          for (const version of ['1.2', '1.1'] as const) {
            const doc = parseAs<{
              nodes: {
                label: string;
                key: string[];
                doc?: string;
                properties: { name: string; doc?: string }[];
              }[];
              edges: { type: string; from: string[]; to: string[] }[];
            }>(out, version);
            expect(doc.nodes[0]?.label).toBe(label);
            expect(doc.nodes[0]?.key).toEqual(keys);
            expect(doc.nodes[0]?.doc).toBe(nodeDoc === '' ? undefined : nodeDoc);
            expect(doc.nodes[0]?.properties[0]?.name).toBe(propName);
            expect(doc.nodes[0]?.properties[0]?.doc).toBe(propDoc === '' ? undefined : propDoc);
            expect(doc.edges[0]).toMatchObject({ type: edgeType, from: keys, to: [label] });
          }
          expect(out).not.toMatch(/[ \t]$/m);
        },
      ),
      { numRuns: 200 },
    );
  });
});

describe('spliceGeneratedRegion (SD-2, SD-3, SD-7)', () => {
  // Lines that cannot start with '#', so they can never be mistaken for a marker.
  const bodyLines = fc
    .array(
      fc.string({ unit: 'grapheme-ascii' }).map((s) => `x${s}\n`),
      { maxLength: 4 },
    )
    .map((ls) => ls.join(''));
  const tail = fc.string({ unit: 'grapheme-ascii' });

  it('replaces exactly the bytes between the marker lines and preserves everything else (SD-2)', () => {
    fc.assert(
      fc.property(
        bodyLines,
        tail,
        bodyLines,
        bodyLines,
        tail,
        bodyLines,
        (pre, bt, old, region, et, post) => {
          const begin = `${GENERATED_BEGIN}${bt}\n`;
          const end = `${GENERATED_END}${et}\n`;
          const file = pre + begin + old + end + post;
          expect(spliceGeneratedRegion(file, region)).toBe(pre + begin + region + end + post);
        },
      ),
    );
  });

  it('is idempotent (SD-3)', () => {
    fc.assert(
      fc.property(bodyLines, bodyLines, bodyLines, bodyLines, (pre, old, region, post) => {
        const file = pre + BEGIN_LINE + old + END_LINE + post;
        const once = spliceGeneratedRegion(file, region);
        expect(spliceGeneratedRegion(once, region)).toBe(once);
      }),
    );
  });

  it.each([
    ['an empty old region', BEGIN_LINE + END_LINE, 'r\n', BEGIN_LINE + 'r\n' + END_LINE],
    ['an empty new region', BEGIN_LINE + 'old\n' + END_LINE, '', BEGIN_LINE + END_LINE],
    [
      'an END line with no trailing newline',
      `a\n${BEGIN_LINE}old\n${GENERATED_END}`,
      'r\n',
      `a\n${BEGIN_LINE}r\n${GENERATED_END}`,
    ],
    [
      'marker text that is not at line start (not a marker)',
      `  ${GENERATED_BEGIN}\n  ${GENERATED_END}\n${BEGIN_LINE}old\n${END_LINE}`,
      'r\n',
      `  ${GENERATED_BEGIN}\n  ${GENERATED_END}\n${BEGIN_LINE}r\n${END_LINE}`,
    ],
    [
      'CRLF outside the region is preserved byte-for-byte',
      `a\r\n${BEGIN_LINE}old\n${END_LINE}b\r\n`,
      'r\n',
      `a\r\n${BEGIN_LINE}r\n${END_LINE}b\r\n`,
    ],
  ])('handles %s', (_name, file, region, expected) => {
    expect(spliceGeneratedRegion(file, region)).toBe(expected);
  });

  it.each([
    [
      'no BEGIN line',
      `a\n${END_LINE}`,
      'schema-doc: expected exactly one line starting with "# BEGIN GENERATED", found 0',
    ],
    [
      'no END line',
      `${BEGIN_LINE}a\n`,
      'schema-doc: expected exactly one line starting with "# END GENERATED", found 0',
    ],
    [
      'two BEGIN lines',
      `${BEGIN_LINE}${BEGIN_LINE}${END_LINE}`,
      'schema-doc: expected exactly one line starting with "# BEGIN GENERATED", found 2',
    ],
    [
      'two END lines',
      `${BEGIN_LINE}${END_LINE}${END_LINE}`,
      'schema-doc: expected exactly one line starting with "# END GENERATED", found 2',
    ],
    [
      'END before BEGIN',
      `${END_LINE}${BEGIN_LINE}`,
      'schema-doc: "# END GENERATED" precedes "# BEGIN GENERATED"',
    ],
    [
      'an empty file',
      '',
      'schema-doc: expected exactly one line starting with "# BEGIN GENERATED", found 0',
    ],
  ])('throws on %s instead of appending', (_name, file, message) => {
    expect(() => spliceGeneratedRegion(file, 'r\n')).toThrow(message);
  });
});

describe('docs/outline/04-schema.yaml stays valid and honest about the relocation (SD-10)', () => {
  const text = readFileSync(join(__dirname, '../../../../docs/outline/04-schema.yaml'), 'utf8');
  const doc = parseAs<Record<string, any>>(text);

  it('parses, with exactly the code labels and edge types in code order', () => {
    expect(doc.nodes.map((n: { label: string }) => n.label)).toEqual(
      NODE_LABELS.map((n) => n.label),
    );
    expect(doc.edges.map((e: { type: string }) => e.type)).toEqual(EDGE_TYPES.map((e) => e.type));
  });

  it('holds the Joern alignment outside the generated region, keyed by exactly the labels and types (D2)', () => {
    expect(new Set(Object.keys(doc.joern_alignment.nodes))).toEqual(
      new Set(NODE_LABELS.map((n) => n.label)),
    );
    expect(new Set(Object.keys(doc.joern_alignment.edges))).toEqual(
      new Set(EDGE_TYPES.map((e) => e.type)),
    );
    // markers matched at line start: the header prose also names them in backticks
    const begin = text.search(/^# BEGIN GENERATED.*$/m);
    const end = text.search(/^# END GENERATED/m);
    expect(begin).toBeGreaterThanOrEqual(0);
    expect(end).toBeGreaterThan(begin);
    const region = text.slice(begin, end);
    expect(region).toContain('nodes:');
    expect(region).not.toMatch(/^\s+joern:/m);
    expect(region).not.toContain('reserved_edges');
    // the splicer agrees: what remains outside the region keeps the hand-maintained keys
    const outside = spliceGeneratedRegion(text, '');
    expect(outside).toContain('joern_alignment:');
    expect(outside).toContain('reserved_edges');
  });

  it('documents the id encoding next to the id rule, with DIRECTORY examples (U1.1.3 leftover)', () => {
    expect(doc.id_rule.encoding).toBeDefined();
    const enc = doc.id_rule.encoding;
    for (const [key, needle] of [
      ['esc_path', '%25'],
      ['esc_path', '%3A'],
      ['esc_seg', '%2E'],
      ['module_scope', '$root'],
      ['directory', 'dir:.'],
      ['body_hash', '#'],
    ] as const)
      expect(enc[key]).toContain(needle);
    expect(doc.id_rule.examples.DIRECTORY).toBe('dir:src');
    expect(doc.id_rule.examples.DIRECTORY_ROOT).toBe('dir:.');
  });
});
